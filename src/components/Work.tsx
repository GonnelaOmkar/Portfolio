import "./styles/Work.css";
import WorkImage from "./WorkImage";
import gsap from "gsap";
import { ScrollTrigger } from "gsap/ScrollTrigger";
import { useGSAP } from "@gsap/react";

gsap.registerPlugin(useGSAP);

const projects = [
  {
    name: "Hybrid Recommendation System",
    category: "AI / ML",
    tools: "Python, FastAPI, Google Gemini API, scikit-learn, MongoDB, Parquet",
    description:
      "Built a hybrid recommendation engine for movies, books, and music combining content-based filtering with collaborative filtering (SVD) and Gemini-powered explanations.",
  },
  {
    name: "SafeStreet",
    category: "Computer Vision",
    tools: "Python, PyTorch, YOLOv5, OpenCV",
    description:
      "Trained a YOLOv5 model to detect and classify road defects with severity tiers. Built a mobile app for GHMC field workers and a severity-sorted dashboard.",
  },
  {
    name: "CineSearch",
    category: "Web App",
    tools: "React, React Router, TMDb API, Axios, Vercel",
    description:
      "Built a responsive movie discovery app with live search, debouncing, genre-based filtering, persistent watchlist, and CI/CD deployment on Vercel.",
  },
];

const Work = () => {
  useGSAP(() => {
    let translateX: number = 0;

    function setTranslateX() {
      const box = document.getElementsByClassName("work-box");
      const rectLeft = document
        .querySelector(".work-container")!
        .getBoundingClientRect().left;
      const rect = box[0].getBoundingClientRect();
      const parentWidth = box[0].parentElement!.getBoundingClientRect().width;
      let padding: number =
        parseInt(window.getComputedStyle(box[0]).padding) / 2;
      translateX = rect.width * box.length - (rectLeft + parentWidth) + padding;
    }

    setTranslateX();

    let timeline = gsap.timeline({
      scrollTrigger: {
        trigger: ".work-section",
        start: "top top",
        end: `+=${translateX}`,
        scrub: true,
        pin: true,
        id: "work",
      },
    });

    timeline.to(".work-flex", {
      x: -translateX,
      ease: "none",
    });

    return () => {
      timeline.kill();
      ScrollTrigger.getById("work")?.kill();
    };
  }, []);

  return (
    <div className="work-section" id="work">
      <div className="work-container section-container">
        <h2>
          My <span>Projects</span>
        </h2>
        <div className="work-flex">
          {projects.map((project, index) => (
            <div className="work-box" key={index}>
              <div className="work-info">
                <div className="work-title">
                  <h3>0{index + 1}</h3>
                  <div>
                    <h4>{project.name}</h4>
                    <p>{project.category}</p>
                  </div>
                </div>
                <h4>Tools and features</h4>
                <p>{project.tools}</p>
              </div>
              <WorkImage image="/images/placeholder.webp" alt={project.name} />
            </div>
          ))}
        </div>
      </div>
    </div>
  );
};

export default Work;
